import { readFileSync, writeFileSync } from 'node:fs'
const info = JSON.parse(readFileSync('build-info.json', 'utf8'))
const methods = [...readFileSync('packages/contracts/rpc.ts', 'utf8').split('] as const')[0].matchAll(/'([^']+)'/g)].map(match => match[1])
const kotlin = `package io.hdsinterlude.android\n\n// Generated by scripts/build-contracts.mjs.\ninternal object RuntimeContract {\n    const val VERSION = "${info.version}"\n    const val CORE = "${info.core}"\n    const val CONTRACT = ${info.contract}\n    val methods = setOf(${methods.map(method => `"${method}"`).join(', ')})\n}\n`
const files = { 'android/app/src/main/java/io/hdsinterlude/android/RuntimeContract.kt': kotlin }
for (const [path, content] of Object.entries(files)) {
  if (process.argv.includes('--check')) { if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) throw new Error(`Stale generated contract: ${path}`) }
  else writeFileSync(path, content)
}
for (const path of ['package.json', 'package-lock.json', 'runtime/sources.lock.json']) {
  const json = JSON.parse(readFileSync(path, 'utf8'))
  if (process.argv.includes('--check')) { if (json.version !== info.version) throw new Error(`Version drift: ${path}`) }
  else { json.version = info.version; if (json.packages?.['']) json.packages[''].version = info.version; writeFileSync(path, JSON.stringify(json, null, 2) + '\n') }
}
